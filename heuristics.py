"""
heuristics.py — слой 0: бесплатные правила, ноль вызовов ИИ.

ЗАЧЕМ ЭТОТ СЛОЙ ВООБЩЕ НУЖЕН.
Мы уже проверяли на реальных данных коллектора: структурное поле
priv_dorm="да" встречается у 12 из 5530 строк и однозначно значит
«это общежитие/комната, не квартира» — определять это через LLM было
бы тратой токенов на то, что уже лежит в данных бесплатно. Этот слой
ловит всё, что можно решить БЕЗ модели, и до неё доходит только
реальный остаток.

На источнике (FETCH_URL = /arenda/kvartiry/) массового потока "комната
выдана за квартиру" физически быть не должно — раздел "комнаты" на
krisha отдельный, и его сюда не парсят. Проверено: 0 совпадений
паттерна "сдам комнату" в заголовках на всей текущей базе. Так что
основная ценность ИИ-слоя, скорее всего, будет не в детекции комнат
(их почти нет), а в более тонких признаках — несоответствие текста и
цены, явно поддельные объявления, требующие капремонта и т.п. Слой 0
всё равно нужен: он бесплатный и отсекает то немногое очевидное, что
есть уже сейчас, и то, что появится с новыми структурными полями.

ЧТО ВОЗВРАЩАЕТ classify().
    None            — не смогли решить бесплатно, нужен ИИ
    dict с вердиктом — решили точно, ИИ не нужен

Формат вердикта одинаковый что от heuristics, что от LLM (см.
openai_batch.py) — чтобы cleaner_db.py не знал, откуда вердикт пришёл.
"""
import os
import re

# Потолок площади, ниже которого priv_dorm=да считается комнатой в
# общежитии, а не квартирой в бывшем общежитии. 25 м² выбрано по пилоту:
# верные срабатывания были на 15, 18 и 20 м², ложные — на 35 и 95 м².
DORM_MAX_AREA_M2 = float(os.environ.get("DORM_MAX_AREA_M2", "25"))

ROOM_TITLE_PATTERNS = [
    re.compile(r"сдам\s+комнат", re.IGNORECASE),
    re.compile(r"комнат[ауы]\s+в\s+общежит", re.IGNORECASE),
    re.compile(r"место\s+в\s+общежит", re.IGNORECASE),
]


def _verdict(usable, reason_code, confidence, reason, source="rule"):
    return {
        "usable": usable,
        "reason_code": reason_code,
        "confidence": confidence,
        "reason": reason,
        "source": source,
    }


def classify(row):
    """row — dict с полями baseline (см. build_baseline.py: master_db._TYPE_SQL,
    типы уже приведены при сборке, площадь/цена — числа, не строки).

    Возвращает вердикт (dict) или None, если нужен ИИ.
    """
    # priv_dorm НЕ является самодостаточным признаком — проверено на живом
    # пилоте (200 объявлений). На krisha это тип ЗДАНИЯ: "приватизированное
    # общежитие" значит, что дом когда-то был общежитием, а не что сдаётся
    # койко-место. Из 7 отбракованных этим правилом минимум одно было явно
    # нормальной квартирой: 4-комнатная, 95 м², 2/5 этаж (id 1015697884),
    # и ещё одно спорным ("сдам 1 комнатую квартиру семейным", 35 м²).
    #
    # Цена такой ошибки выше обычной: правило стоит ДО модели и закорачивает
    # её, то есть текст объявления вообще никто не читает, а вердикт
    # выставляется с confidence=high и потому не всплывает в /verdicts/review.
    #
    # Поэтому правило оставлено только там, где оно совпадает с площадью
    # комнаты. Всё, что крупнее, уходит в ИИ — само поле priv_dorm теперь
    # передаётся модели в тексте объявления (см. openai_batch._format_listing),
    # так что сигнал не теряется, а лишь перестаёт быть приговором.
    priv_dorm = (row.get("priv_dorm") or "").strip().lower()
    if priv_dorm == "да":
        try:
            area = float(row.get("square_m2") or 0)
        except (TypeError, ValueError):
            area = 0
        if 0 < area < DORM_MAX_AREA_M2:
            return _verdict(
                False, "dormitory", "high",
                f"priv_dorm=да и площадь {area:.0f} м² — комната в общежитии",
            )
        # Площадь как у квартиры (или неизвестна) — решать должна модель
        # по тексту, а не поле. Проваливаемся дальше, в итоге вернём None.

    title = row.get("title") or ""
    for pat in ROOM_TITLE_PATTERNS:
        if pat.search(title):
            return _verdict(
                False, "room", "high",
                "заголовок содержит явный паттерн сдачи комнаты",
            )

    # Нестандартное состояние: цена такой квартиры несравнима с обычной
    # сдачей и портит базу сравнения. Решаем по полям, которые хозяин сам
    # выбрал на сайте, — точно и без токенов. ПУСТОЕ поле сюда не попадает:
    # «не заполнил» — это «не знаем», решать будет модель по тексту.
    # Мебель «частично» тоже не отбраковывается — это обычная сдача.
    if (row.get("rent_renovation") or "").strip().lower() == "без ремонта":
        return _verdict(
            False, "no_renovation", "high",
            "поле сайта: без ремонта — цена несравнима со стандартной сдачей",
        )
    if (row.get("furniture") or "").strip().lower() == "без мебели":
        return _verdict(
            False, "unfurnished", "high",
            "поле сайта: без мебели — цена несравнима со стандартной сдачей",
        )

    # Площадь сама по себе НЕ основание для вердикта "комната" — она
    # входит в санитарные фильтры build_baseline (там уже отсеяно
    # <15 м²), а между 15 и 16 остаётся серая зона легитимных студий.
    # Здесь она только помечает случай как "нужен ИИ с осторожностью",
    # возвращая None, а не готовый вердикт.

    return None
